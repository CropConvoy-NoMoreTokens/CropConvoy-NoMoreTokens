import { test } from 'node:test';
import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import type { AddressInfo } from 'node:net';
import { createApp } from '../src/app.js';
import { createDependencies } from '../src/core/dependencies.js';
const fixture = JSON.parse(await readFile(new URL('../../contracts/fixtures/happy-path.json', import.meta.url), 'utf8'));
test('starter endpoints validate requests, expose stubs, and never fabricate routing', async (t) => {
  const deps = createDependencies({ stub: true, maxPlanMs: 45000 });
  const server = createApp(deps, ['http://localhost:5173']).listen(0, '127.0.0.1');
  await new Promise<void>(resolve => server.once('listening', resolve));
  t.after(async () => { await new Promise<void>((resolve, reject) => server.close(error => error ? reject(error) : resolve())); await deps.db.close(); });
  const base = `http://127.0.0.1:${(server.address() as AddressInfo).port}`;
  const post = (path: string, input: unknown) => fetch(base + path, { method: 'POST', headers: { 'Content-Type': 'application/json' }, body: JSON.stringify(input) });
  const health = await fetch(base + '/health');
  assert.equal(health.status, 200);
  assert.equal((await health.json()).meta.mode, 'stub');
  assert.equal((await fetch(base + '/ready')).status, 503);
  assert.equal((await post('/api/listings', { ...fixture.listingInput, confirmed: false })).status, 422);
  assert.equal((await post('/api/listings', { ...fixture.listingInput, quantityKg: -1 })).status, 422);
  const created = await post('/api/listings', fixture.listingInput);
  assert.equal(created.status, 201);
  const listing = (await created.json()).data;
  assert.equal((await (await fetch(base + '/api/listings/' + listing.id)).json()).data.quantityKg, 80);
  const order = await post('/api/orders', fixture.orderInput);
  assert.equal(order.status, 201);
  assert.equal((await (await fetch(base + '/api/orders')).json()).data.length, 1);
  const extraction = (await (await post('/api/harvest/extract', fixture.extractInput)).json());
  assert.equal(extraction.data.draft.quantityKg, null);
  assert.equal(extraction.meta.mode, 'stub');
  const generation = await post('/api/plans/generate', { listingId: listing.id });
  const result = await generation.json();
  assert.equal(result.data.plan, null);
  assert.equal(result.data.searchComplete, false);
  assert.equal(result.meta.mode, 'stub');
  assert.equal((await post('/api/trips', fixture.tripInput)).status, 503);
  assert.equal((await post('/api/plans/generate', { listingId: fixture.ids.listingId })).status, 404);
  assert.equal((await post('/api/plans/' + fixture.ids.planId + '/decision', { decision: 'accept' })).status, 404);
  assert.equal((await fetch(base + '/health', { headers: { Origin: 'https://unapproved.example' } })).status, 403);
  assert.equal((await fetch(base + '/missing')).status, 404);
});
